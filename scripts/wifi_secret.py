# Fallback Wi-Fi credentials outside the repo.
#
# Used only when FRAM holds no valid credentials (blank or failed FRAM). Values come from
# ~/.secrets/iot.env (IOT_WIFI_FALLBACK_SSID / IOT_WIFI_FALLBACK_PASSWORD) and land in a generated
# header, same mechanism as scripts/ota_secret.py: no -D flags, so project.checksum stays constant
# and a shell without iot.env never triggers a full rebuild.
#
# Missing variables = empty fallback (warning, not an error): the node then stays off Wi-Fi until
# provisioning, which is the intended behaviour once the fallback is no longer wanted.

import os

Import("env")

SSID_VAR = "IOT_WIFI_FALLBACK_SSID"
PASS_VAR = "IOT_WIFI_FALLBACK_PASSWORD"

ssid = os.environ.get(SSID_VAR, "")
password = os.environ.get(PASS_VAR, "")

if not ssid:
    print("*** NOTE: %s not set — firmware without Wi-Fi fallback (FRAM credentials only)" % SSID_VAR)


def c_str(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


gen_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
header = os.path.join(gen_dir, "wifi_secret.h")
content = (
    "#pragma once\n"
    "// Generated by scripts/wifi_secret.py — do not edit\n"
    "#define WIFI_FALLBACK_SSID %s\n"
    "#define WIFI_FALLBACK_PASSWORD %s\n" % (c_str(ssid), c_str(password if ssid else ""))
)

# Write only on change — constant mtime = no recompilation of config.cpp
old = None
if os.path.isfile(header):
    with open(header, encoding="utf8") as f:
        old = f.read()
if old != content:
    os.makedirs(gen_dir, exist_ok=True)
    with open(header, "w", encoding="utf8") as f:
        f.write(content)

env.Append(CPPPATH=[gen_dir])
